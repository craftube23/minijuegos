/**
 * ==============================================================================
 * DATOS Y PARTITURAS MUSICALES - SINFONÍA DE CAMPANAS (Rhythm Songs & Charts)
 * ==============================================================================
 * 
 * Contiene las definiciones de canciones, BPM, velocidades de notas y las
 * partituras rítmicas completas sincronizadas en segundos (time) y compases (b).
 */

export interface ChartNoteRecord {
  lane: number; // 0: Rojo (←), 1: Dorado (↓), 2: Verde (↑), 3: Azul (→)
  time: number; // Segundo exacto en la canción
  isStar?: boolean; // Nota especial con Logo (x4 Multiplicador)
  logoType?: 1 | 2; // 1: Feria Mágica, 2: Campuslands
}

export interface BeatPatternNote {
  lane: number;
  b: number; // Posición en compases musicales
  isStar?: boolean;
  logoType?: 1 | 2;
}

export interface SongDef {
  id: string;
  title: string;
  subtitle: string;
  bpm: number;
  speed: number;
  durationSeconds: number;
  stars: number;
  difficultyLabel: string;
  tagColor: string;
  audioFile: string;
  icon: string;
}

