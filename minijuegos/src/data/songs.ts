/**
 * Generador rítmico asistido que crea partituras equilibradas con notas normales y sustain
 */
function buildArcadeRhythmChart(
  bpm: number,
  durationSec: number,
  startOffsetSec: number,
  intensity: number,
  sustainFrequency: number = 0.22
): ChartNoteRecord[] {
  const notes: ChartNoteRecord[] = [];
  const beatSec = 60 / bpm;
  let t = startOffsetSec;
  let lastLane = -1;
  let starCounter = 0;

  // Patrones rítmicos arcade variados
  const lanePatterns = [
    [0, 1, 2, 3],
    [3, 2, 1, 0],
    [0, 2, 1, 3],
    [1, 0, 2, 3],
    [0, 1, 0, 2, 3],
    [3, 1, 2, 0],
    [1, 2, 1, 2],
    [0, 3, 1, 2]
  ];

  let patternIdx = 0;
  let noteIndexInPattern = 0;

  while (t < durationSec - 4.0) {
    const currentPattern = lanePatterns[patternIdx % lanePatterns.length];
    let lane = currentPattern[noteIndexInPattern % currentPattern.length];
    if (lane === lastLane && Math.random() > 0.4) {
      lane = (lane + 1 + Math.floor(Math.random() * 3)) % 4;
    }
    lastLane = lane;
    noteIndexInPattern++;

    if (noteIndexInPattern >= currentPattern.length) {
      noteIndexInPattern = 0;
      patternIdx++;
    }

    starCounter++;
    const isStar = starCounter % (intensity >= 4 ? 12 : 9) === 0;
    const isSustain = Math.random() < sustainFrequency;

    if (isSustain) {
      const holdBeats = Math.random() > 0.6 ? 2.5 : 1.5;
      const duration = Math.round(holdBeats * beatSec * 100) / 100;
      notes.push({
        lane,
        time: Math.round(t * 100) / 100,
        duration,
        type: "sustain",
        isStar,
        logoType: isStar ? (starCounter % 2 === 0 ? 2 : 1) : undefined
      });
      // Avanzar el tiempo considerando la duración del sustain + pausa
      t += duration + beatSec * (intensity >= 4 ? 0.75 : 1.25);
    } else {
      notes.push({
        lane,
        time: Math.round(t * 100) / 100,
        duration: 0,
        type: "normal",
        isStar,
        logoType: isStar ? (starCounter % 2 === 0 ? 2 : 1) : undefined
      });

      // Intervalo hasta la siguiente nota según la intensidad de la canción
      let stepBeats = 1.0;
      if (intensity >= 5) {
        stepBeats = Math.random() > 0.45 ? 0.5 : 1.0;
      } else if (intensity >= 4) {
        stepBeats = Math.random() > 0.6 ? 0.5 : 1.0;
      } else if (intensity >= 3) {
        stepBeats = Math.random() > 0.75 ? 0.75 : 1.0;
      } else if (intensity === 2) {
        stepBeats = Math.random() > 0.5 ? 1.0 : 1.5;
      } else {
        stepBeats = Math.random() > 0.5 ? 1.5 : 2.0;
      }

      t += stepBeats * beatSec;
    }
  }

  return notes;
}

