/**
 * Renderiza el marcado SVG vectorizado para el icono solicitado
 */
export function renderBannerIcon(
  iconName?: BannerIconName,
  size: number = 16,
  customClass: string = ""
): string {
  if (!iconName || !ICON_REGISTRY[iconName]) return "";

  const nodes = ICON_REGISTRY[iconName];
  const innerSvg = nodes
    .map(([tag, attrs]) => {
      const attrStr = Object.entries(attrs)
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ");
      return `<${tag} ${attrStr}></${tag}>`;
    })
    .join("");

  const cls = `banner-svg-icon banner-icon-${iconName} ${customClass}`.trim();

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" class="${cls}" aria-hidden="true">${innerSvg}</svg>`;
}
